  assert((await grid.locator('.wb-pg-row[data-id=type] img').count()) === 1, 'enum icon next to the choice');
  assert((await grid.locator('.wb-pg-row[data-id=gravity] input').inputValue()) === '3.7', 'Mercury gravity shown');
  await grid.locator('.wb-pg-row[data-id=gravity] input').fill('-1'); await grid.locator('.wb-pg-row[data-id=gravity] input').press('Enter'); await settle(500);
  assert(await grid.locator('.wb-pg-row[data-id=gravity]').evaluate(e => e.classList.contains('wb-pg-error')), 'negative gravity rejected by the setter');
  assert((await grid.locator('.wb-pg-row[data-id=gravity] input').inputValue()) === '3.7', 'value restored');
  await grid.locator('.wb-pg-row[data-id=moons] input').fill('2'); await grid.locator('.wb-pg-row[data-id=moons] input').press('Enter'); await settle(600);
  assert((await T('widgetLog').textContent()) === 'property: moons=2', 'typed edit applied: ' + await T('widgetLog').textContent());
