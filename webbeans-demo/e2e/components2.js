  await T('busy').click(); await settle(300);
  assert(await T('busyPanel').locator('.wb-busy-overlay').isVisible(), 'busy overlay shown');
  await settle(1800);
  assert(!(await T('busyPanel').locator('.wb-busy-overlay').count()) && (await T('widgetLog').textContent()) === 'busy: done', 'overlay removed after the timer');

