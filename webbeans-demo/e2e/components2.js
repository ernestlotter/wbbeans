  assert((await T('widgetLog').textContent()) === 'property: type=ICE_GIANT', 'enum edit applied');
  await typeSel.selectOption('ROCKY'); await settle(400);
  await grid.locator('.wb-pg-row[data-id=moons] input').fill('0'); await grid.locator('.wb-pg-row[data-id=moons] input').press('Enter'); await settle(400);
  const tt = T('treeTable');
  const rows = tt.locator('.wb-table-row[data-key]');
