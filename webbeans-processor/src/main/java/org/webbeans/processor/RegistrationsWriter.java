package org.webbeans.processor;

import java.io.IOException;
import java.io.Writer;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.Map;

import javax.annotation.processing.Filer;
import javax.annotation.processing.ProcessingEnvironment;
import javax.lang.model.element.Element;
import javax.tools.FileObject;
import javax.tools.JavaFileObject;
import javax.tools.StandardLocation;

import org.webbeans.processor.spi.Literals;
import org.webbeans.processor.spi.RegistrationModel;

/** Writes {@code <module>.generated.WbRegistrations} and its {@code META-INF/services} registration. */
final class RegistrationsWriter {

    static final String PROVIDER = "org.webbeans.core.registry.RegistrationProvider";
    static final String CLASS_NAME = "WbRegistrations";

    private final ProcessingEnvironment env;
    private final List<String> classes = new ArrayList<String>();
    private final Set<String> writtenHidden = new HashSet<String>();
    private int writtenEntries;

    RegistrationsWriter(ProcessingEnvironment env) {
        this.env = env;
    }

    /**
     * Writes the entries collected since the last call as one {@code WbRegistrations[n]} class. Called at the end
     * of every round that saw annotations, so the class is never created in the final round (javac warns about
     * that) and sources generated by other processors still get their own class.
     */
    void writeRound(RegistrationModel model, String module) throws IOException {
        List<RegistrationModel.EntrySpec> entries = model.getEntries().subList(writtenEntries, model.getEntries().size());
        List<String> hidden = new ArrayList<String>();
        for (String h : model.getHidden()) {
            if (writtenHidden.add(h)) {
                hidden.add(h);
            }
        }
        if (entries.isEmpty() && hidden.isEmpty()) {
            return;
        }
        String pkg = module + ".generated";
        String name = classes.isEmpty() ? CLASS_NAME : CLASS_NAME + (classes.size() + 1);
        String fqcn = pkg + "." + name;
        Element[] origins = model.getOrigins().toArray(new Element[0]);
        JavaFileObject src = env.getFiler().createSourceFile(fqcn, origins);
        Writer w = src.openWriter();
        try {
            w.write("package " + pkg + ";\n\n");
            w.write("/** Generated by the WebBeans annotation processor from the module's registration annotations. Do not edit. */\n");
            w.write("public final class " + name + " implements org.webbeans.core.registry.RegistrationProvider {\n\n");
            w.write("    @Override\n");
            w.write("    public void register(org.webbeans.core.registry.RegistrationBuilder b) {\n");
            for (RegistrationModel.EntrySpec e : entries) {
                w.write(statement(e));
            }
            for (String h : hidden) {
                w.write("        b.hide(" + Literals.string(h) + ");\n");
            }
            w.write("    }\n}\n");
        } finally {
            w.close();
        }
        writtenEntries = model.getEntries().size();
        classes.add(fqcn);
    }

    /** Writes the {@code META-INF/services} file naming every generated class; called in the final round. */
    void writeServices(RegistrationModel model) throws IOException {
        if (classes.isEmpty()) {
            return;
        }
        Element[] origins = model.getOrigins().toArray(new Element[0]);
        FileObject services = env.getFiler().createResource(StandardLocation.CLASS_OUTPUT, "", "META-INF/services/" + PROVIDER, origins);
        Writer sw = services.openWriter();
        try {
            for (String c : classes) {
                sw.write(c + "\n");
            }
        } finally {
            sw.close();
        }
    }

    static String statement(RegistrationModel.EntrySpec e) {
        StringBuilder sb = new StringBuilder("        b.");
        String path = Literals.string(e.getPath());
        switch (e.getKind()) {
            case INSTANCE:
                sb.append("instance(").append(path).append(')');
                break;
            case REFERENCE:
                sb.append("reference(").append(path).append(", ").append(Literals.string(e.getTarget())).append(')');
                break;
            case SEPARATOR:
                sb.append("separatorAt(").append(path).append(')');
                break;
            case FOLDER:
                sb.append("folder(").append(path).append(')');
                break;
            default:
                throw new AssertionError(e.getKind());
        }
        if (e.getFactoryExpression() != null) {
            sb.append("\n            .").append(e.isSupplier() ? "supplier(" : "factory(").append(e.getFactoryExpression()).append(')');
        }
        if (e.getInstanceOf() != null) {
            sb.append("\n            .instanceOf(").append(e.getInstanceOf()).append(".class)");
        }
        if (e.getBundle() != null) {
            sb.append("\n            .bundle(").append(Literals.string(e.getBundle())).append(')');
        }
        for (Map.Entry<String, String> a : e.getAttrs().entrySet()) {
            sb.append("\n            .attr(").append(Literals.string(a.getKey())).append(", ").append(a.getValue()).append(')');
        }
        if (e.getPosition() != Integer.MAX_VALUE) {
            sb.append("\n            .position(").append(e.getPosition()).append(')');
        }
        if (!e.getRoles().isEmpty()) {
            sb.append("\n            .roles(");
            boolean first = true;
            for (String r : e.getRoles()) {
                if (!first) {
                    sb.append(", ");
                }
                first = false;
                sb.append(Literals.string(r));
            }
            sb.append(')');
        }
        return sb.append(";\n").toString();
    }
}
